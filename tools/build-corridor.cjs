'use strict';
// Concatenate Substructure's sources (tools/corridor-manifest.json) into corridor.bundle.js,
// the module script corridor.html loads. The sources are one function body: they share one scope
// inside init(THREE), in manifest order, so a later file can call anything an earlier one declares.
// The wrapper loads Three.js and the page font (the signs and plan board are drawn with it once, at
// load), and reports a renderer that cannot start.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'corridor.bundle.js');
const MANIFEST = path.join(__dirname, 'corridor-manifest.json');

const readCorridorManifest = () => JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
// Line endings follow the checkout (core.autocrlf), so normalise them before comparing or writing.
const read = rel => fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');

const HEAD = `// GENERATED by tools/build-corridor.cjs from corridor/*.js - edit those, then npm run build
const notice = document.getElementById('notice');
const restarting = new URLSearchParams(location.search).has('restart');
async function restartProgress(value) {
  if (!restarting) return;
  document.getElementById('restart-progress').value = value;
  // Yield after completed work so the browser can paint the real loading milestones.
  await new Promise(resolve => requestAnimationFrame(() => setTimeout(resolve,0)));
}
try {
  const [THREE] = await Promise.all([
    import('https://unpkg.com/three@0.155.0/build/three.module.js'),
    document.fonts.load('16px ISOCPEUR').catch(() => {}),
  ]);
  await restartProgress(20);
  await init(THREE);
} catch (error) {
  notice.textContent = 'The renderer could not start. Reload to try again.';
  document.getElementById('enter-label').textContent = 'UNAVAILABLE';
  if (restarting) document.getElementById('restart-label').textContent = 'RESTART FAILED — RELOAD TO TRY AGAIN';
  console.error(error);
}
async function init(THREE) {
`;

function buildCorridor() {
  const milestones = { 'corridor/service-tunnel.js': 45,'corridor/surface.js': 75,'corridor/assemble.js': 85 };
  const sources = readCorridorManifest().sources.map(rel => read(rel) +
    (milestones[rel] ? `if (restarting) await restartProgress(${milestones[rel]});\n` : '')).join('');
  return HEAD + sources + '}\n';
}

module.exports = { buildCorridor, readCorridorManifest, OUT };

if (require.main === module) {
  const out = buildCorridor();
  fs.writeFileSync(OUT, out);
  console.log('built corridor.bundle.js: ' + Buffer.byteLength(out) + ' bytes');
}
