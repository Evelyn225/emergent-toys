#!/usr/bin/env python3
"""Build PlantHUD, a tall condensed, proportionally spaced CRT-overlay
bitmap font.

Glyphs are drawn on an 8x16 pixel grid (caps/digits) with 4 extra rows for
descenders. Vertical strokes are 2px and horizontals 1px, with hooked
terminals and bar-end serifs like the reference overlay.

    pip install fonttools brotli
    python3 tools/build-planthud-font.py

Writes PlantHUD.ttf, PlantHUD.woff2 and PlantHUD.woff to the repo root.
"""
import os
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

PX = 100          # font units per pixel
W = 8             # glyph width in pixels
ADV = 10          # advance width of .notdef in pixels
GAP = 3           # pixels between glyphs
SPACE = 7         # advance width of the space in pixels
# Fixed advances (pixels): tabular digits, narrow cells for small punctuation.
FIXED = dict({d: 11 for d in "0123456789"}, **{p: 8 for p in ".,:;"})
CAP = 16          # cap height in pixels
DESC = 4          # descender rows
UPM = 2000        # one pixel per grid cell at multiples of 20px

# 16-row glyphs sit on the baseline; 20-row glyphs include descender rows.
G = {}


def g(ch, art):
    rows = [r for r in art.strip("\n").split("\n")]
    rows = [r.strip() for r in rows]
    assert len(rows) in (CAP, CAP + DESC), (ch, len(rows))
    for r in rows:
        assert len(r) == W, (ch, r)
    G[ch] = rows


