NAMES = {" ": "space", "●": "uni25CF", "°": "degree"}


def glyph_name(ch):
    if ch in NAMES:
        return NAMES[ch]
    if ch.isascii() and ch.isalpha():
        return ch
    return "uni%04X" % ord(ch)


def ink(rows):
    """Leftmost and rightmost lit columns, or None for a blank glyph."""
    cols = [c for r in rows for c, v in enumerate(r) if v == "#"]
    return (min(cols), max(cols)) if cols else None


def draw(rows, shift):
    """Merge each row's runs of lit pixels into rectangles."""
    pen = TTGlyphPen(None)
    for r, line in enumerate(rows):
        top = (CAP - r) * PX
        bot = top - PX
        c = 0
        while c < W:
            if line[c] == "#":
                s = c
                while c < W and line[c] == "#":
                    c += 1
                x0, x1 = (shift + s) * PX, (shift + c) * PX
                pen.moveTo((x0, bot))
                pen.lineTo((x0, top))
                pen.lineTo((x1, top))
                pen.lineTo((x1, bot))
                pen.closePath()
            else:
                c += 1
    return pen.glyph()


def build(out_dir):
    # Proportional spacing, like the reference: each glyph keeps one pixel
    # of side bearing on the left and gets its ink width plus GAP pixels,
    # except the FIXED ones.
    order = [".notdef"] + [glyph_name(c) for c in G]
    glyphs = {".notdef": draw(["########"] + ["#......#"] * 14 + ["########"], 1)}
    metrics = {".notdef": (ADV * PX, PX)}
    cmap = {}
    for ch, rows in G.items():
        n = glyph_name(ch)
        span = ink(rows)
        if span is None:
            glyphs[n] = draw(rows, 0)
            metrics[n] = (SPACE * PX, 0)
        else:
            lo, hi = span
            fixed = FIXED.get(ch)
            if fixed:
                # digits share one width and small punctuation one narrow
                # cell, ink centred in it
                left = (fixed - (hi - lo + 1)) // 2
                glyphs[n] = draw(rows, left - lo)
                metrics[n] = (fixed * PX, left * PX)
            else:
                glyphs[n] = draw(rows, 1 - lo)
                metrics[n] = ((hi - lo + 1 + GAP) * PX, PX)
        cmap[ord(ch)] = n

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    asc, desc = (CAP + 1) * PX, DESC * PX
    fb.setupHorizontalHeader(ascent=asc, descent=-desc)
    fb.setupNameTable({"familyName": "PlantHUD", "styleName": "Regular",
                       "version": "Version 1.000"})
    fb.setupOS2(sTypoAscender=asc, sTypoDescender=-desc, sTypoLineGap=0,
                usWinAscent=asc, usWinDescent=desc,
                sxHeight=10 * PX, sCapHeight=CAP * PX)
    fb.setupPost()
    fb.font["post"].underlinePosition = -3 * PX

    base = os.path.join(out_dir, "PlantHUD")
    fb.save(base + ".ttf")
    for flavor in ("woff", "woff2"):
        fb.font.flavor = flavor
        fb.font.save(base + "." + flavor)
    print("wrote", base + ".{ttf,woff,woff2}", len(cmap), "glyphs")


if __name__ == "__main__":
    build(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
