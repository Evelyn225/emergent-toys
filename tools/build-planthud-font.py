NAMES = {" ": "space", "●": "uni25CF", "°": "degree"}


def glyph_name(ch):
    if ch in NAMES:
        return NAMES[ch]
    if ch.isascii() and ch.isalpha():
        return ch
    return "uni%04X" % ord(ch)


def draw(rows):
    """Merge each row's runs of lit pixels into rectangles."""
    pen = TTGlyphPen(None)
    left = (ADV - W) // 2
    for r, line in enumerate(rows):
        top = (CAP - r) * PX
        bot = top - PX
        c = 0
        while c < W:
            if line[c] == "#":
                s = c
                while c < W and line[c] == "#":
                    c += 1
                x0, x1 = (left + s) * PX, (left + c) * PX
                pen.moveTo((x0, bot))
                pen.lineTo((x0, top))
                pen.lineTo((x1, top))
                pen.lineTo((x1, bot))
                pen.closePath()
            else:
                c += 1
    return pen.glyph()


def build(out_dir):
    order = [".notdef"] + [glyph_name(c) for c in G]
    glyphs = {".notdef": draw(["######"] + ["#....#"] * 10 + ["######"])}
    cmap = {}
    for ch, rows in G.items():
        n = glyph_name(ch)
        glyphs[n] = draw(rows)
        cmap[ord(ch)] = n
    metrics = {n: (ADV * PX, 0) for n in order}

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    asc, desc = (CAP + 1) * PX, DESC * PX
    fb.setupHorizontalHeader(ascent=asc, descent=-desc)
    fb.setupNameTable({"familyName": "PlantHUD", "styleName": "Regular",
                       "version": "Version 1.000"})
    fb.setupOS2(sTypoAscender=asc, sTypoDescender=-desc, sTypoLineGap=0,
                usWinAscent=asc, usWinDescent=desc,
                sxHeight=8 * PX, sCapHeight=CAP * PX)
    fb.setupPost(isFixedPitch=1)
    fb.font["post"].underlinePosition = -2 * PX

    base = os.path.join(out_dir, "PlantHUD")
    fb.save(base + ".ttf")
    for flavor in ("woff", "woff2"):
        fb.font.flavor = flavor
        fb.font.save(base + "." + flavor)
    print("wrote", base + ".{ttf,woff,woff2}", len(cmap), "glyphs")


if __name__ == "__main__":
    build(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
