W = 6             # glyph width in pixels
ADV = 8           # advance width in pixels
CAP = 12          # cap height in pixels
DESC = 3          # descender rows
UPM = 1600

# 12-row glyphs sit on the baseline; 15-row glyphs include descender rows.
G = {}


def g(ch, art):
    rows = [r for r in art.strip("\n").split("\n")]
    rows = [r.strip() for r in rows]
    assert len(rows) in (CAP, CAP + DESC), (ch, len(rows))
    for r in rows:
        assert len(r) == W, (ch, r)
    G[ch] = rows


