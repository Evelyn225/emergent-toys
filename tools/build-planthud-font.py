NAMES = {" ": "space", "●": "uni25CF", "°": "degree"}


def glyph_name(ch):
    if ch in NAMES:
        return NAMES[ch]
    if ch.isascii() and ch.isalpha():
        return ch
    return "uni%04X" % ord(ch)


def ink(rows):
    """Leftmost and rightmost lit columns, or None for a blank glyph."""
    cols = [c for r in rows for c, v in enumerate(r) if v == "#"]
    return (min(cols), max(cols)) if cols else None


def draw(rows, shift):
    """Trace the lit pixels as merged outlines, one contour per shape edge.

    Each pixel used to be part of its own row rectangle, so a glyph was a
    stack of rectangles that only touched. Some renderers (notably Apple's)
    leave hairline seams where separate contours meet, which shows up as
    faint lines through the letters. Tracing the outline of the union
    instead leaves no internal edges at all.

    Edges run clockwise around ink (ink on the right), so holes come out
    counter-clockwise, as TrueType expects.
    """
    lit = {(c, r) for r, line in enumerate(rows) for c, v in enumerate(line) if v == "#"}

    def pt(c, r):
        # grid corner (column c, row line r) to font units; row 0 is the top
        return ((shift + c) * PX, (CAP - r) * PX)

    # Boundary edges between a lit pixel and an unlit neighbour, as pairs of
    # grid corners (column, row line), directed with the ink on the right.
    edges = {}
    for c, r in lit:
        if (c - 1, r) not in lit:
            edges.setdefault((c, r + 1), []).append((c, r))          # left side, up
        if (c, r - 1) not in lit:
            edges.setdefault((c, r), []).append((c + 1, r))          # top, rightwards
        if (c + 1, r) not in lit:
            edges.setdefault((c + 1, r), []).append((c + 1, r + 1))  # right side, down
        if (c, r + 1) not in lit:
            edges.setdefault((c + 1, r + 1), []).append((c, r + 1))  # bottom, leftwards

    def turn_order(prev, cur, nxt):
        # Where two shapes touch only at a corner, prefer turning right so
        # each contour stays around its own shape: right, straight, left.
        dx1, dy1 = cur[0] - prev[0], cur[1] - prev[1]
        dx2, dy2 = nxt[0] - cur[0], nxt[1] - cur[1]
        cross = dx1 * dy2 - dy1 * dx2   # grid y grows downward here
        return 0 if cross > 0 else 1 if cross == 0 else 2

    pen = TTGlyphPen(None)
    while edges:
        start = min(edges)
        loop = [start]
        cur = start
        prev = None
        while True:
            outs = edges[cur]
            if prev is not None and len(outs) > 1:
                outs.sort(key=lambda n: turn_order(prev, cur, n))
            nxt = outs.pop(0)
            if not outs:
                del edges[cur]
            prev, cur = cur, nxt
            if cur == start:
                break
            loop.append(cur)
        # drop corners in the middle of straight runs
        pts = [p for i, p in enumerate(loop)
               if (loop[i - 1][0] - p[0]) * (loop[(i + 1) % len(loop)][1] - p[1])
               != (loop[i - 1][1] - p[1]) * (loop[(i + 1) % len(loop)][0] - p[0])]
        pen.moveTo(pt(*pts[0]))
        for p in pts[1:]:
            pen.lineTo(pt(*p))
        pen.closePath()
    return pen.glyph()


def build(out_dir):
    # Proportional spacing, like the reference: each glyph keeps one pixel
    # of side bearing on the left and gets its ink width plus GAP pixels,
    # except the FIXED ones.
    order = [".notdef"] + [glyph_name(c) for c in G]
    glyphs = {".notdef": draw(["########"] + ["#......#"] * 14 + ["########"], 1)}
    metrics = {".notdef": (ADV * PX, PX)}
    cmap = {}
    for ch, rows in G.items():
        n = glyph_name(ch)
        span = ink(rows)
        if span is None:
            glyphs[n] = draw(rows, 0)
            metrics[n] = (SPACE * PX, 0)
        else:
            lo, hi = span
            fixed = FIXED.get(ch)
            if fixed:
                # digits share one width and small punctuation one narrow
                # cell, ink centred in it
                left = (fixed - (hi - lo + 1)) // 2
                glyphs[n] = draw(rows, left - lo)
                metrics[n] = (fixed * PX, left * PX)
            else:
                glyphs[n] = draw(rows, 1 - lo)
                metrics[n] = ((hi - lo + 1 + GAP) * PX, PX)
        cmap[ord(ch)] = n

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    asc, desc = (CAP + 1) * PX, DESC * PX
    fb.setupHorizontalHeader(ascent=asc, descent=-desc)
    fb.setupNameTable({"familyName": "PlantHUD", "styleName": "Regular",
                       "version": "Version 1.000"})
    fb.setupOS2(sTypoAscender=asc, sTypoDescender=-desc, sTypoLineGap=0,
                usWinAscent=asc, usWinDescent=desc,
                sxHeight=10 * PX, sCapHeight=CAP * PX)
    fb.setupPost()
    fb.font["post"].underlinePosition = -3 * PX

    base = os.path.join(out_dir, "PlantHUD")
    fb.save(base + ".ttf")
    for flavor in ("woff", "woff2"):
        fb.font.flavor = flavor
        fb.font.save(base + "." + flavor)
    print("wrote", base + ".{ttf,woff,woff2}", len(cmap), "glyphs")


if __name__ == "__main__":
    build(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
